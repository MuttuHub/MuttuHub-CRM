// GET /api/v1/projects/:id — one project ficha (contract E-06, P02).
// PATCH /api/v1/projects/:id — general data of a BORRADOR project (E-06, P06).
//
// PATCH accepts nombre, origen, fecha_inicio, fecha_fin, valor_total,
// beneficiarios_meta, responsable_id, `lineas` (N..N replacement) and
// `municipio_ids` (N..N replacement). Every scalar write, both join
// replacements and all audit rows happen in ONE transaction (ADR-05,
// REQ-AUD-03); the audit is one row per changed field and per changed line or
// municipio (REQ-AUD-04).
//
// Deliberately absent here: `POST` (needs the S2.2 autogenerated code), the
// eligible-opportunities and opportunity-conversion endpoints (S2.3), the
// `DIFERENCIA_VALOR` alert (S2.4), `miembro_ids` (S2.6) and any UI.

import { NextResponse } from "next/server";
import { OrigenProyecto, Prisma } from "@prisma/client";
import { z } from "zod";
import { db } from "@/lib/db";
import { apiError, parseJsonBody } from "@/lib/api/errors";
import { withApiErrorHandling } from "@/lib/api/handler";
import { requireApiUser } from "@/lib/supabase/server";
import { parseDate } from "@/lib/api/crm";
import { canManageProjects } from "@/lib/permissions";
import { diffFields, logChanges, type CambioInput } from "@/lib/api/audit-cambios";
import { validarLineas } from "@/lib/proyectos/proyecto-general";
import {
  AUDITED_PROJECT_FIELDS,
  PROJECT_SELECT_V2,
  canReadProject,
  checkLineasExisten,
  checkMunicipiosExisten,
  checkResponsableActivo,
  diffLineas,
  diffMunicipios,
  invalidStateError,
  toProjectItemV2,
  type ProjectRowV2,
} from "@/lib/api/projects";

export const dynamic = "force-dynamic";

type RouteContext = { params: Promise<{ id: string }> };

/** Fields the PATCH can write, and the audit diff watches. */
type ProjectPatch = Partial<Pick<ProjectRowV2, (typeof AUDITED_PROJECT_FIELDS)[number]>>;

const INVALID_DATE_MESSAGES = {
  fecha_inicio: "La fecha de inicio no es válida.",
  fecha_fin: "La fecha de fin no es válida.",
} as const;

export const PROJECT_PATCH_SCHEMA = z.object({
  nombre: z
    .string()
    .trim()
    .min(1, "El nombre no puede estar vacío.")
    .max(200, "El nombre es muy largo.")
    .optional(),
  origen: z
    .enum(OrigenProyecto, { error: "Origen de proyecto no válido." })
    .nullable()
    .optional(),
  fecha_inicio: z
    .string()
    .refine((value) => parseDate(value) !== null, INVALID_DATE_MESSAGES.fecha_inicio)
    .nullable()
    .optional(),
  fecha_fin: z
    .string()
    .refine((value) => parseDate(value) !== null, INVALID_DATE_MESSAGES.fecha_fin)
    .nullable()
    .optional(),
  valor_total: z.number().min(0, "El valor total no puede ser negativo.").nullable().optional(),
  beneficiarios_meta: z
    .number()
    .int("La meta de beneficiarios debe ser un número entero.")
    .min(0, "La meta de beneficiarios no puede ser negativa.")
    .nullable()
    .optional(),
  responsable_id: z.string().min(1, "El responsable no puede estar vacío.").nullable().optional(),
  lineas: z
    .array(
      z.object({
        id: z.string().min(1, "La línea estratégica no es válida."),
        principal: z.boolean().optional(),
      }),
    )
    .min(1, "Selecciona al menos una línea estratégica.")
    .optional(),
  municipio_ids: z
    .array(z.string().min(1, "El municipio no es válido."))
    .min(1, "Selecciona al menos un municipio.")
    .refine((ids) => new Set(ids).size === ids.length, "No repitas el mismo municipio.")
    .optional(),
});

/**
 * Fields that only exist through another unit or must not change here. They are
 * refused with a 400 instead of being silently dropped: `miembro_ids` belongs
 * to S2.6, `codigo` to S2.2, `estado` to baseline approval (S8.1) and
 * `alertas`/`diferencia_valor_oportunidad` to S2.4.
 */
const PATCH_FORBIDDEN_FIELDS = [
  "codigo",
  "estado",
  "cliente_id",
  "oportunidad_id",
  "umbrales_override",
  "programacion_pendiente",
  "deleted_at",
  "diferencia_valor_oportunidad",
  "alertas",
  "miembro_ids",
] as const;

/** `@db.Date` stores the calendar day: keep the UTC midnight the column reads back. */
function normalizeDate(value: string): Date {
  const date = parseDate(value)!;
  date.setUTCHours(0, 0, 0, 0);
  return date;
}

export const GET = withApiErrorHandling(
  "projects",
  "No pudimos cargar el proyecto. Inténtalo de nuevo.",
  async (_request: Request, ctx: RouteContext) => {
    const auth = await requireApiUser();
    if (!auth.ok) return auth.response;
    const { id } = await ctx.params;

    const row = await db.proyecto.findFirst({
      where: { id, deleted_at: null },
      select: PROJECT_SELECT_V2,
    });
    if (!row) {
      return apiError("El proyecto no existe.", 404, "NOT_FOUND");
    }

    // Existence is settled first; visibility is a read-scope decision. A
    // project the actor may not read is a 403, not a 404 (REQ-ACC-02).
    if (!canReadProject(auth.usuario)) {
      return apiError("No tienes permisos sobre este proyecto.", 403, "FORBIDDEN");
    }

    return NextResponse.json({ proyecto: toProjectItemV2(row) });
  },
);

export const PATCH = withApiErrorHandling(
  "projects",
  "No pudimos actualizar el proyecto. Inténtalo de nuevo.",
  async (request: Request, ctx: RouteContext) => {
    const auth = await requireApiUser();
    if (!auth.ok) return auth.response;
    const { id } = await ctx.params;

    const existente = await db.proyecto.findFirst({
      where: { id, deleted_at: null },
      select: PROJECT_SELECT_V2,
    });
    if (!existente) {
      return apiError("El proyecto no existe.", 404, "NOT_FOUND");
    }

    // P06: editing general data is ADM/GER authority — a COORDINADOR needs no
    // membership lookup to be denied here (REQ-ACC-01).
    if (!canManageProjects(auth.usuario)) {
      return apiError("No tienes permisos sobre este proyecto.", 403, "FORBIDDEN");
    }

    if (existente.estado !== "BORRADOR") {
      return invalidStateError(
        "Solo se pueden editar los datos generales de un proyecto en Borrador.",
      );
    }

    const body = await parseJsonBody<Record<string, unknown>>(request);
    if (body === null) {
      return apiError("Cuerpo de la solicitud no válido.", 400, "VALIDATION_ERROR");
    }

    for (const field of PATCH_FORBIDDEN_FIELDS) {
      if (field in body) {
        return apiError(
          `El campo '${field}' no se puede modificar en este endpoint.`,
          400,
          "VALIDATION_ERROR",
        );
      }
    }

    const parsed = PROJECT_PATCH_SCHEMA.safeParse(body);
    if (!parsed.success) {
      return apiError(
        parsed.error.issues[0]?.message ?? "Datos no válidos.",
        400,
        "VALIDATION_ERROR",
      );
    }

    const patch: ProjectPatch = {};
    if (parsed.data.nombre !== undefined) patch.nombre = parsed.data.nombre;
    if (parsed.data.origen !== undefined) patch.origen = parsed.data.origen;
    if (parsed.data.fecha_inicio !== undefined) {
      patch.fecha_inicio =
        parsed.data.fecha_inicio === null ? null : normalizeDate(parsed.data.fecha_inicio);
    }
    if (parsed.data.fecha_fin !== undefined) {
      patch.fecha_fin =
        parsed.data.fecha_fin === null ? null : normalizeDate(parsed.data.fecha_fin);
    }
    if (parsed.data.valor_total !== undefined) {
      // The column is Decimal(15,2); rounding here keeps the audited value
      // equal to the one the record ends up holding.
      patch.valor_total =
        parsed.data.valor_total === null
          ? null
          : new Prisma.Decimal(parsed.data.valor_total).toDecimalPlaces(2);
    }
    if (parsed.data.beneficiarios_meta !== undefined) {
      patch.beneficiarios_meta = parsed.data.beneficiarios_meta;
    }
    if (parsed.data.responsable_id !== undefined) {
      patch.responsable_id = parsed.data.responsable_id;
    }

    const lineas = parsed.data.lineas;
    const municipioIds = parsed.data.municipio_ids;

    if (Object.keys(patch).length === 0 && lineas === undefined && municipioIds === undefined) {
      return apiError("Envía al menos un campo para actualizar.", 400, "VALIDATION_ERROR");
    }

    if (lineas !== undefined) {
      const validacion = validarLineas(lineas);
      if (!validacion.ok) {
        return apiError(validacion.message, 400, "VALIDATION_ERROR");
      }
    }

    // Cross-field rule the column cannot express: fecha_fin > fecha_inicio.
    const inicio = "fecha_inicio" in patch ? patch.fecha_inicio : existente.fecha_inicio;
    const fin = "fecha_fin" in patch ? patch.fecha_fin : existente.fecha_fin;
    if (inicio && fin && fin.getTime() < inicio.getTime()) {
      return apiError("La fecha de fin no puede ser anterior a la de inicio.", 400, "VALIDATION_ERROR");
    }

    if (lineas !== undefined) {
      const missing = await checkLineasExisten(lineas);
      if (missing) return missing;
    }
    if (municipioIds !== undefined) {
      const missing = await checkMunicipiosExisten(municipioIds);
      if (missing) return missing;
    }
    if (patch.responsable_id) {
      const inactive = await checkResponsableActivo(patch.responsable_id);
      if (inactive) return inactive;
    }

    // One audit row per changed field (REQ-AUD-04), plus one per changed line
    // and per changed municipio. All of them share the lote `logChanges`
    // generates, so the edit reads back as one operation.
    const auditBase = {
      usuario_id: auth.usuario.id,
      accion: "EDITAR" as const,
      entidad: "proyecto",
      entidad_id: id,
      proyecto_id: id,
    };
    const cambios: CambioInput[] = diffFields(existente, patch, AUDITED_PROJECT_FIELDS).map(
      (cambio) => ({
        ...auditBase,
        campo: cambio.campo,
        valor_anterior: cambio.valor_anterior,
        valor_nuevo: cambio.valor_nuevo,
      }),
    );
    if (lineas !== undefined) {
      cambios.push(
        ...diffLineas(
          existente.lineas.map((link) => ({ id: link.linea.id, principal: link.principal })),
          lineas.map((linea) => ({ id: linea.id, principal: linea.principal === true })),
        ).map((cambio) => ({ ...auditBase, ...cambio })),
      );
    }
    if (municipioIds !== undefined) {
      cambios.push(
        ...diffMunicipios(
          existente.municipios.map((link) => link.municipio.id),
          municipioIds,
        ).map((cambio) => ({ ...auditBase, ...cambio })),
      );
    }

    const row = await db.$transaction(async (tx) => {
      // Join replacements first: the re-read below then sees the new sets.
      if (lineas !== undefined) {
        await tx.proyectoLinea.deleteMany({ where: { proyecto_id: id } });
        await tx.proyectoLinea.createMany({
          data: lineas.map((linea) => ({
            proyecto_id: id,
            linea_id: linea.id,
            principal: linea.principal === true,
          })),
        });
      }
      if (municipioIds !== undefined) {
        await tx.proyectoMunicipio.deleteMany({ where: { proyecto_id: id } });
        await tx.proyectoMunicipio.createMany({
          data: municipioIds.map((municipio_id) => ({ proyecto_id: id, municipio_id })),
        });
      }
      if (Object.keys(patch).length > 0) {
        await tx.proyecto.update({ where: { id }, data: patch });
      }

      const fresh = await tx.proyecto.findUniqueOrThrow({
        where: { id },
        select: PROJECT_SELECT_V2,
      });

      if (cambios.length > 0) {
        await logChanges(tx, cambios);
      }

      return fresh;
    });

    return NextResponse.json({ proyecto: toProjectItemV2(row) });
  },
);
